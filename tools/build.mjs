// Builds dist/study-app.html: one self-contained file (CSS, JS, data and every image inlined).
// Usage: node tools/build.mjs
import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
let html = read('index.html');

// 1. images: every path listed in figmeta.js -> data URI
const figmetaSrc = read('app/data/figmeta.js');
const FIGMETA = JSON.parse(figmetaSrc.slice(figmetaSrc.indexOf('{'), figmetaSrc.lastIndexOf('}') + 1));
const paths = new Set();
for (const f of Object.values(FIGMETA)) {
  paths.add(f.img);
  for (const p of Object.values(f.panels || {})) paths.add(p.img);
}
const MIME = { '.webp': 'image/webp', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.svg': 'image/svg+xml' };
const imgData = {};
let imgBytes = 0;
for (const p of paths) {
  const buf = readFileSync(join(ROOT, p));
  imgBytes += buf.length;
  imgData[p] = `data:${MIME[extname(p)]};base64,${buf.toString('base64')}`;
}
const safe = (s) => s.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

// 2. inline the stylesheet
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) => `<style>\n${read(href)}\n</style>`);

// 3. inline every script; the image map goes in before the first script
let first = true;
html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
  let out = '';
  if (first) {
    out += `<script>window.IMG_DATA=${JSON.stringify(imgData)};</script>\n`;
    first = false;
  }
  return out + `<script>/* ${src} */\n${safe(read(src))}\n</script>`;
});
html = html.replace('<title>', '<!-- Single-file build of the study app. Generated by tools/build.mjs; do not edit by hand. -->\n<title>');

mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, 'dist', 'study-app.html'), html);
const size = statSync(join(ROOT, 'dist', 'study-app.html')).size;
console.log(`dist/study-app.html written: ${(size / 1e6).toFixed(2)} MB (${paths.size} images, ${(imgBytes / 1e6).toFixed(2)} MB raw)`);
